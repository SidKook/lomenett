names = list(ICONS.keys())
with open('../icons_user.h', 'w') as header:
    header.write('// icons_user.h -- user-selectable 16x16 entry icons (generated by sim/gen_icons.py).\n')
    header.write('// Letters A-Z and digits 0-9 follow these at runtime as drawn badges.\n#pragma once\n')
    header.write('#define USER_PICTO_N %d\n' % len(names))
    header.write('static const uint8_t PROGMEM USER_PICTO[USER_PICTO_N][32] = {\n')
    for name in names:
        icon_bytes = []
        for row in ICONS[name][1]:
            row_bits = int(''.join('1' if pixel == '#' else '0' for pixel in row), 2)
            icon_bytes += [row_bits >> 8, row_bits & 0xFF]          # two bytes per row, MSB = leftmost
        header.write('  { ' + ', '.join('0x%02X' % value for value in icon_bytes) + ' },  // ' + name + '\n')
    header.write('};\nstatic const char *USER_PICTO_NAME[USER_PICTO_N] = { ' + ', '.join('"%s"' % name for name in names) + ' };\n')
    header.write('static const char *USER_PICTO_SHORT[USER_PICTO_N] = { ' + ', '.join('"%s"' % ICONS[name][0] for name in names) + ' };\n')
print(len(names), "pictograms ->", len(names) + 36, "icons total")
