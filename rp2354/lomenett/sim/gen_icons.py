# gen_icons.py -- generates ../icons_user.h: 16x16 1-bit pictograms from ASCII
# art ('#' = pixel on). Letters and digits are drawn at runtime, not here.
# Run from sim/: python3 gen_icons.py
ICONS = {}   # name -> (short name, 16 rows of 16 chars)

def icon(name, short_name, art):
    rows = art.strip('\n').split('\n')
    assert len(rows) == 16, (name, len(rows))
    for row in rows:
        assert len(row) == 16, (name, row, len(row))
    ICONS[name] = (short_name, rows)

